export type PanelVerdict = { ok: true } | { ok: false; title: string; text: string };

/** Проверка пульта: красная кнопка — авария, перерасход — банкротство, жёлтый газон в ноябре — поле погибло */
export function panelVerdict(picks: number[]): PanelVerdict {
    const sum = picks.reduce((s, lv, i) => s + PANEL.systems[i].levels[lv].cost, 0);
    const red = picks.findIndex((lv, i) => PANEL.systems[i].levels[lv].tone === 'red');
    if (red >= 0) return { ok: false, title: 'Инженерная авария!', text: PANEL.systems[red].levels[picks[red]].note };
    if (sum > PANEL.budget)
        return {
            ok: false,
            title: 'Перерасход бюджета!',
            text: 'Стадион — банкрот, счета арестованы. Снизь мощность там, где переплатил за излишества.',
        };
    if (PANEL.systems[0].levels[picks[0]].tone !== 'green')
        return {
            ok: false,
            title: 'Поле пожелтело',
            text: 'В ноябре без фитоламп газон желтеет, и комиссия лиги снижает оценку. Спаси поле, а сэкономь на том, что не нужно каждый день.',
        };
    return { ok: true };
}

/** Проверка открытого ответа: число — по цифрам, слово — по корню без регистра и «ё» */
export function checkOpenAnswer(answers: string[], input: string): boolean {
    const text = input.toLowerCase().replace(/ё/g, 'е').trim();
    if (!text) return false;
    if (answers.every((a) => /^\d+$/.test(a))) return answers.includes(text.replace(/\D/g, ''));
    return answers.some((a) => text.includes(a.replace(/ё/g, 'е')));
}
