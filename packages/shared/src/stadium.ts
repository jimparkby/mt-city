// открытые вопросы (ответ словом или числом), вопросы с выбором ответа и мини-игра.

import type { PathStep } from './paths.js';

export type MiniGameId = 'director' | 'auditor' | 'talks' | 'panel';

/** Этап мини-игры: выбор решения или расчёт */
export type MiniStage =
    | {
          kind: 'choice';
          title: string;
          text: string;
          q: string;
          opts: string[];
          a: number;
          /** Разбор правильного решения */
          ok: string;
          /** Разбор каждого неверного варианта (по индексу) */
          bad: Record<number, string>;
      }
    | { kind: 'number'; title: string; text: string; q: string; answer: number; hint: string; ok: string };

export interface MiniScenario {
    title: string;
    legend: string;
    stages: MiniStage[];
    /** Звание за прохождение и итог */
    rank: string;
    finale: string;
}

