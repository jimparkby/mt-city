const LESSON = 10;
const QUESTION = 20;
const GAME = 60;

const lesson = (block: string, t: string, say: string, text: { h?: string; p: string }[]): PathStep => ({
    block,
    t,
    kind: 'lesson',
    r: LESSON,
    say,
    text,
});

const open = (block: string, t: string, q: string, answers: string[], hint: string, why: string): PathStep => ({
    block,
    t,
    kind: 'open',
    r: QUESTION,
    say: 'Ответ — одно-два слова или число.',
    q,
    answers,
    hint,
    why,
});

const quiz = (block: string, t: string, q: string, opts: string[], a: number, why: string): PathStep => ({
    block,
    t,
    kind: 'quiz',
    r: QUESTION,
    say: 'Выбери один ответ.',
    q,
    opts,
    a,
    why,
});

const game = (block: string, t: string, say: string, id: MiniGameId): PathStep => ({
    block,
    t,
    kind: 'game',
    r: GAME,
    say,
    game: id,
});

