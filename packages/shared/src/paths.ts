export type StepKind = 'lesson' | 'quiz' | 'sim' | 'work';

export interface PathStep {
    t: string;
    kind: StepKind;
    /** Награда: MTcoin (7–13) или очки знаний (14–17), целые */
    r: number;
    say: string;
    q?: string;
    opts?: string[];
    /** Индекс правильного ответа */
    a?: number;
    why?: string;
}

export interface LocationPath {
    /** Цвет фона шапки локации */
    c: string;
    tip: string;
    kid: PathStep[];
    teen: PathStep[];
}

type RawQuiz = [title: string, question: string, opts: string[], answer: number] | 'SIM';

